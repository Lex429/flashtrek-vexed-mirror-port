"""Build immutable physical debris metadata from the game's original ship artwork.

Run from any directory: python tools/build-debris-geometry.py [--check].
This is an offline source-asset build, not a performance benchmark. It uses the
same bounded preparation owner as the game and never exports regenerated art.
"""
import argparse
import functools
import hashlib
import http.server
import json
import os
from pathlib import Path
import threading

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT/'html-games/broken-mirror-port/ship-debris-geometry.js'
ART = 'html-games/flashtrek-broken-mirror/'
SOURCE_MODULES = [
    'cthia-effects.js', 'olympic-effects.js', 'tug-effects.js',
    'constitution-tug-effects.js', 'starter-effects.js', 'earth-profiles.js',
    'klingon-profiles.js', 'romulan-profiles.js', 'vulcan-profiles.js',
    'cardassian-profiles.js', 'ferengi-dominion-profiles.js',
    'independent-profiles.js', 'earth-effects.js', 'wreckage-effects.js',
    'bioship-effects.js', 'lifeform-effects.js', 'showcase-stage-fragments.js',
    'cthia-destruction.js', 'ship-art-readback.js',
    'showcase-assets/catalog.json',
]
EXTRACT = r'''async type=>{
 const definition=nativeShipDefinitions.get(type,'civilian'),profile=nativeShipDefinitions.artworkProfile(type);
 if(definition.renderer)return null;
 if(!profile)throw Error('Registered hull lacks an artwork profile '+type);
 const value=await nativeShipEffects.prepare(type,'civilian');
 if(!value?.optionalReady||value.assets.length!==4||value.assets.some(asset=>!asset?.art))throw Error('Incomplete preparation '+type);
 const omitted=new Set(['texture','lit','edge','hot','side','material']);
 const plain=value=>{
   if(value===undefined)return undefined;
   if(value===null||typeof value==='boolean'||typeof value==='string')return value;
   if(typeof value==='number'){if(!Number.isFinite(value))throw Error('Nonfinite geometry '+type);return value;}
   if(Array.isArray(value))return value.map(plain);
   if(typeof value!=='object'||Object.getPrototypeOf(value)!==Object.prototype)throw Error('Native geometry field '+type);
   return Object.fromEntries(Object.entries(value).filter(([key,item])=>!omitted.has(key)&&item!==undefined).map(([key,item])=>[key,plain(item)]));
 };
 const config=value=>typeof value==='function'?{$function:String(value)}:Array.isArray(value)?value.map(config):
   value&&typeof value==='object'?Object.fromEntries(Object.keys(value).sort().filter(key=>key!=='effects'&&key!=='biology').map(key=>[key,config(value[key])])):value;
 const catalog=await (await fetch('../flashtrek-broken-mirror/showcase-assets/catalog.json')).json(),frames=catalog.ships.find(ship=>ship.id===type)?.frames||definition.artwork.frames;
 const fragments=plain(value.fragments||[[],[],[],[]]),wrecks=plain(value.destruction?.serialized?.()||[]);
 if(fragments.length!==4||wrecks.length!==(profile.destruction?4:0)||wrecks.some(stage=>stage.sourcePixels!==stage.cutPixels))throw Error('Invalid conserved geometry '+type+' '+JSON.stringify({fragments:fragments.length,wrecks:wrecks.map(s=>({source:s.sourcePixels,cut:s.cutPixels})),hasDestruction:!!profile.destruction}));
 return {name:definition.name,width:value.assets[0].width,height:value.assets[0].height,
   frameFiles:frames,fragments,wrecks,hasDestruction:!!profile.destruction,profileConfig:config(profile)};
}'''


def canonical(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'), sort_keys=True)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def source_bytes(file):
    data=(ROOT/file).read_bytes()
    return data.replace(b'\r\n',b'\n') if Path(file).suffix.lower() in ['.js','.json','.html'] else data


def serialize(data):
    return ('/* Generated by tools/build-debris-geometry.py from original aligned artwork.\n'
            '   Physical metadata only: regenerate and check when frames/profiles change. */\n'
            '(() => {\n  "use strict";\n  const data = '+canonical(data)+';\n'
            '  const freeze = value => { if(value && typeof value === "object") {\n'
            '    for(const item of Object.values(value)) freeze(item); Object.freeze(value);\n'
            '  } return value; };\n  window.VexedMirrorDebrisGeometry = freeze(data);\n})();\n')


class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *_args):
        pass


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Rebuild all geometry and require byte-identical source data')
    parser.add_argument('--types', help='Comma-separated original hull IDs; compare these records without rewriting the complete asset')
    args = parser.parse_args()
    server = http.server.ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(Quiet, directory=str(ROOT)))
    threading.Thread(target=server.serve_forever, daemon=True).start()
    errors, ships = [], {}
    try:
        with sync_playwright() as p:
            channel = os.environ.get('BROWSER_CHANNEL', 'msedge')
            browser = p.chromium.launch(headless=True, **({'channel': channel} if channel else {}))
            page = browser.new_page(viewport={'width': 1280, 'height': 850})
            page.set_default_timeout(300000)
            page.on('pageerror', lambda error: errors.append(str(error)))
            page.goto(f'http://127.0.0.1:{server.server_port}/html-games/broken-mirror-port/index.html')
            page.wait_for_function('()=>nativeCombatShots.isReady() && document.querySelector("#startup").hidden', timeout=120000)
            page.evaluate('()=>{window.requestAnimationFrame=()=>0;window.nativeSimulation={...nativeSimulation,blocked:()=>true};window.nativeSimulationHost?.checkpoint();}')
            types = [int(value) for value in args.types.split(',')] if args.types else page.evaluate('nativeShipDefinitions.registered().filter(d=>!d.renderer).map(d=>d.id).sort((a,b)=>a-b)')
            for index, ship_type in enumerate(types):
                row = page.evaluate(EXTRACT, ship_type)
                if row is not None:
                    row['profileSignature'] = digest(canonical(row.pop('profileConfig')).replace('\\r\\n','\\n').encode('utf-8'))
                    ships[str(ship_type)] = row
                print(f'Prepared {index+1}/{len(types)}: {ship_type}', flush=True)
            if errors:
                raise AssertionError(errors)
            if args.types:
                expected = page.evaluate('window.VexedMirrorDebrisGeometry?.ships||null')
                if not expected:
                    raise AssertionError('No complete geometry asset is loaded')
                for ship_type, row in ships.items():
                    if canonical(row) != canonical(expected.get(ship_type)):
                        raise AssertionError(f'Original prepared geometry differs for ship {ship_type}')
                print(json.dumps({'checked': len(ships), 'browser': browser.version, 'scope': 'Original artwork metadata equality, no timing claim'}))
                return
            browser.close()
    finally:
        server.shutdown()
    sources = {ART+file for file in SOURCE_MODULES}
    sources.update('html-games/broken-mirror-port/'+file for file in ['flight-assets.js', 'world-data.js', 'flight-reference-data.js'])
    for row in ships.values():
        sources.update(ART+'showcase-assets/'+file for file in row['frameFiles'])
    hashes = {file: digest(source_bytes(file)) for file in sorted(sources)}
    signature = digest(''.join(f'{file}:{value}\n' for file, value in hashes.items()).encode('utf-8'))
    source = serialize({'version': 1, 'sourceSignature': signature, 'sourceFiles': hashes, 'ships': ships})
    if args.check:
        if not DEST.exists() or DEST.read_text(encoding='utf-8') != source:
            raise AssertionError('Debris geometry is stale; run python tools/build-debris-geometry.py')
    else:
        DEST.write_text(source, encoding='utf-8', newline='\n')
    print(json.dumps({'checked': args.check, 'ships': len(ships), 'sourceFiles': len(hashes), 'sourceSignature': signature, 'bytes': len(source.encode('utf-8'))}))


if __name__ == '__main__':
    main()
