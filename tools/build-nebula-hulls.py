"""Build cosmetic alpha-run metadata from the existing aligned hull artwork."""
import argparse
import functools
import hashlib
import http.server
import json
import os
from pathlib import Path
import threading

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'html-games/broken-mirror-port/nebula-hull-masks.js'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()


class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *_args):
        pass


EXTRACT = r'''async ({id,stage})=>{
 const definition=nativeShipDefinitions.get(id),health=definition.hull*[1,.6,.4,.1][stage];let asset;
 if(definition.renderer){await nativeRepairVisuals.ensure();asset=nativeRepairVisuals.fogArtwork({entity:{hull:health}});}
 else asset=await vexedFlightAssets.loadShip(id,health);
 const m=nativeNebulaMaterial.maskFor(asset),runs=[];
 for(let y=0;y<m.h;y++){let value=0,length=0;for(let x=0;x<m.w;x++){const next=m.alpha[y*m.w+x]>=48?1:0;if(next!==value){runs.push(length);length=0;value=next;}length++;}runs.push(length);}
 const bytes=new Uint8Array(runs.length*2);runs.forEach((n,i)=>{bytes[i*2]=n&255;bytes[i*2+1]=n>>8;});let text='';for(const n of bytes)text+=String.fromCharCode(n);
 return {w:m.w,h:m.h,aspect:m.aspect,runs:btoa(text),pivot:asset.fogPivot||null};
}'''

server = http.server.ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(Quiet, directory=str(ROOT)))
threading.Thread(target=server.serve_forever, daemon=True).start()
try:
    with sync_playwright() as p:
        channel = os.environ.get('BROWSER_CHANNEL', '')
        browser = p.chromium.launch(headless=True, **({'channel': channel} if channel else {}))
        page = browser.new_page(viewport=dict(width=1280, height=850))
        page.goto(f'http://127.0.0.1:{server.server_port}/html-games/broken-mirror-port/index.html')
        page.wait_for_function('()=>nativeCombatShots.isReady()&&document.querySelector("#startup").hidden', timeout=120000)
        page.evaluate('startNativeDevGame()')
        page.wait_for_function('()=>nativeNpcDev.getState()?.devMode', timeout=120000)
        page.locator('#devToolsBtn').click()
        page.evaluate('()=>{window.nativeSimulation={...nativeSimulation,blocked:()=>true};nativeSimulationHost.checkpoint();window.requestAnimationFrame=()=>0;}')
        definitions = page.evaluate('nativeShipDefinitions.registered().map(d=>d.id)')
        masks = {}
        for index, ship_type in enumerate(definitions):
            for stage in range(4):
                masks[f'{ship_type}:{stage}'] = page.evaluate(EXTRACT, dict(id=ship_type, stage=stage))
            if index % 20 == 0:
                print(f'Extracted {index+1}/{len(definitions)} hulls', flush=True)
        browser.close()
    payload = dict(version=1, masks=masks)
    content = '/* Generated by tools/build-nebula-hulls.py from aligned artwork. Cosmetic metadata only. */\nwindow.nativeNebulaHullMasks=Object.freeze(' + json.dumps(payload, separators=(',', ':'), sort_keys=True) + ');\n'
    if args.check:
        assert DEST.read_text(encoding='utf8') == content, 'Nebula hull masks differ from the current aligned artwork; rebuild them.'
    else:
        DEST.write_text(content, encoding='utf8')
    print(json.dumps(dict(passed=True, hulls=len(definitions), stages=len(masks), bytes=len(content), sha256=hashlib.sha256(content.encode()).hexdigest())))
finally:
    server.shutdown()
    server.server_close()
