"""Build simulation repair sites from existing art using the Steamrunner analyzer."""
import functools
import http.server
import json
import os
from pathlib import Path
import threading
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[1]
class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self,*args): pass
server=http.server.ThreadingHTTPServer(('127.0.0.1',0),functools.partial(Quiet,directory=str(ROOT)))
threading.Thread(target=server.serve_forever,daemon=True).start()
try:
    with sync_playwright() as p:
        channel=os.environ.get('BROWSER_CHANNEL','msedge')
        browser=p.chromium.launch(headless=True,**({'channel':channel} if channel else {}))
        page=browser.new_page()
        page.goto(f'http://127.0.0.1:{server.server_port}/html-games/broken-mirror-port/index.html')
        page.wait_for_function('()=>!!window.nativeRepairWork')
        ships=page.evaluate(r"""async()=>{
          const catalog=await fetch('../flashtrek-broken-mirror/showcase-assets/catalog.json').then(r=>r.json());
          const result={};
          for(const entry of VexedMirrorWorld.ships){
            const ship=catalog.ships.find(s=>s.id===entry.id);
            const load=async stage=>{
              const image=new Image();image.src='../flashtrek-broken-mirror/showcase-assets/'+ship.frames[stage];await image.decode();
              const profile=starterShips.get(ship.id);
              return profile?profile.align(image,stage):ship.id===57?alignTugFrame(image,stage):ship.id===58?alignOlympicFrame(image,stage):image;
            };
            const intact=await load(0),damaged=await load(3),analysis=nativeRepairWork.analyze(damaged,intact,true);
            const points=[];
            for(const cell of nativeRepairWork.ordered(analysis.regions)){
              const x=Math.max(0,Math.min(analysis.w-1,Math.round(cell.x))),y=Math.max(0,Math.min(analysis.h-1,Math.round(cell.y)));
              points.push(y*analysis.w+x,Math.round(Math.atan2(cell.ny,cell.nx)*1000));
            }
            result[entry.id]={w:analysis.w,h:analysis.h,tile:analysis.tile,changed:analysis.changedPixels,missing:analysis.missingPixels,points};
          }
          return result;
        }""")
        output=ROOT/'html-games/broken-mirror-port/ship-repair-sites.js'
        output.write_text('/* Generated by tools/build-repair-sites.py from existing damage artwork. */\nwindow.VexedRepairSites='+json.dumps({'version':1,'ships':ships},separators=(',',':'))+';\n',encoding='utf-8')
        print(json.dumps({'ships':len(ships),'sites':sum(len(s['points'])//2 for s in ships.values()),'bytes':output.stat().st_size}))
        browser.close()
finally:
    server.shutdown()
