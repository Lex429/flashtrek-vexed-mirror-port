"""Bake nebula collision silhouettes from the actual asteroid damage plates."""
import argparse
import functools
import hashlib
import http.server
import json
import os
from pathlib import Path
import threading

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'html-games/broken-mirror-port/nebula-asteroid-masks.js'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()


class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *_args):
        pass


EXTRACT = r'''async files=>{
 await nativeSolAsteroids.ready;
 // Load predecessors too: deuranium damage is intersected with earlier plates
 // by its artwork owner, exactly as in the live asteroid renderer.
 await Promise.all(files.map(file=>new Promise((resolve,reject)=>{
   nativeSolAsteroids.image(file);const art=nativeSolAsteroids.peekImage(file);
   if(art.complete&&art.naturalWidth)return resolve();
   art.addEventListener('load',resolve,{once:true});art.addEventListener('error',reject,{once:true});
 })));
 const masks={};
 for(const file of files){
   const art=nativeSolAsteroids.image(file),w=160,h=160,c=document.createElement('canvas');c.width=w;c.height=h;
   const g=c.getContext('2d',{willReadFrequently:true});g.drawImage(art,0,0,w,h);
   const rgba=g.getImageData(0,0,w,h).data,runs=[];
   for(let y=0;y<h;y++){let value=0,length=0;for(let x=0;x<w;x++){
     const next=rgba[(y*w+x)*4+3]>=48?1:0;
     if(next!==value){runs.push(length);length=0;value=next;}length++;
   }runs.push(length);}
   const bytes=new Uint8Array(runs.length*2);runs.forEach((n,i)=>{bytes[i*2]=n&255;bytes[i*2+1]=n>>8;});
   let raw='';for(const n of bytes)raw+=String.fromCharCode(n);
   masks[file]={w,h,aspect:1,runs:btoa(raw)};
 }
 return masks;
}'''

catalog = json.loads((ROOT / 'html-games/flashtrek-broken-mirror/showcase-assets/asteroids.json').read_text())
files = set()
for rock in catalog:
    files.add(rock['file'])
    if not rock['file'].endswith(('_light.png', '_heavy.png', '_severe.png')):
        files.update(rock['file'][:-4] + '_' + stage + '.png' for stage in ('light', 'heavy', 'severe'))
files.add('asteroids/asteroid_01_intact.png')
# The owner's damage intersection is recursive; load/prepare plates in order.
files = sorted(files, key=lambda name: (name.endswith('_light.png') + 2*name.endswith('_heavy.png') + 3*name.endswith('_severe.png'), name))
server = http.server.ThreadingHTTPServer(('127.0.0.1', 0), functools.partial(Quiet, directory=str(ROOT)))
threading.Thread(target=server.serve_forever, daemon=True).start()
try:
    with sync_playwright() as p:
        channel = os.environ.get('BROWSER_CHANNEL', 'msedge')
        browser = p.chromium.launch(headless=True, **({'channel': channel} if channel else {}))
        page = browser.new_page()
        # No running game, fleet or fluid worker is needed to bake artwork.
        page.route('**/index.html', lambda route: route.fulfill(content_type='text/html', body='<script>window.nativeSystemHub={sol:[]};</script><script src="sol-asteroids.js"></script>'))
        page.goto(f'http://127.0.0.1:{server.server_port}/html-games/broken-mirror-port/index.html')
        masks = page.evaluate(EXTRACT, files)
        browser.close()
    payload = dict(version=1, threshold=48, masks=masks)
    content = '/* Generated by tools/build-nebula-asteroids.py; original asteroid alpha only. */\nwindow.nativeNebulaAsteroidMasks=Object.freeze(' + json.dumps(payload, separators=(',', ':'), sort_keys=True) + ');\n'
    if args.check:
        assert DEST.read_text(encoding='utf8') == content, 'Asteroid alpha metadata differs; rebuild it.'
    else:
        DEST.write_text(content, encoding='utf8')
    print(json.dumps(dict(passed=True, frames=len(masks), bytes=len(content), sha256=hashlib.sha256(content.encode()).hexdigest())))
finally:
    server.shutdown()
    server.server_close()
