"""Measure the finished armored tug's existing lamp pixels; never rewrite artwork."""
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'html-games/flashtrek-broken-mirror'


def build():
    catalog = json.loads((ART / 'showcase-assets/catalog.json').read_text())
    ship = next(row for row in catalog['ships'] if row['id'] == 416)
    assert ship['damageReady'] and len(set(ship['frames'])) == 4
    image = Image.open(ART / 'showcase-assets' / ship['frames'][0]).convert('RGBA')
    width, height = image.size
    pixels = image.load()
    colors = {'red': '#ff4e35', 'blue': '#4fc3ff', 'amber': '#ffbe5b'}

    def kind(x, y):
        r, g, b, a = pixels[x, y]
        if a < 165:
            return None
        if r > 105 and r > g * 1.43 and r > b * 1.23:
            return 'red'
        if b > 88 and b > r * 1.24 and b > g * 1.08:
            return 'blue'
        if r > 102 and g > 54 and r > g * 1.14 and g > b * 1.19:
            return 'amber'
        return None

    # Use the same connected fixture selection as tug-class-ii-lights.js.
    seen, lights = set(), []
    for y in range(height):
        for x in range(width):
            color = kind(x, y)
            if color is None or (x, y) in seen:
                continue
            group = [(x, y)]
            seen.add((x, y))
            for px, py in group:
                for nx, ny in [(px-1, py), (px+1, py), (px, py-1), (px, py+1)]:
                    if 0 <= nx < width and 0 <= ny < height and (nx, ny) not in seen and kind(nx, ny) == color:
                        seen.add((nx, ny))
                        group.append((nx, ny))
            area = len(group)
            cx, cy = sum(p[0] for p in group)/area, sum(p[1] for p in group)/area
            engine = cy > height * .70 and (cx < width * .28 or cx > width * .72)
            if area < 3 or not (area <= 65 or engine and (color != 'amber' or area <= 190)):
                continue
            left, top = min(p[0] for p in group), min(p[1] for p in group)
            right, bottom = max(p[0] for p in group)+1, max(p[1] for p in group)+1
            runs = []
            for row in range(top, bottom):
                columns = sorted(p[0] for p in group if p[1] == row)
                for column in columns:
                    if runs and runs[-1][0] == row-top and runs[-1][1]+runs[-1][2] == column-left:
                        runs[-1][2] += 1
                    else:
                        runs.append([row-top, column-left, 1])
            lights.append({'x': round(cx, 3), 'y': round(cy, 3), 'left': left, 'top': top,
                           'w': right-left, 'h': bottom-top, 'r': max(3, min(11, area**.5*2.4)),
                           'kind': 'core' if engine else 'running', 'offSevere': True,
                           'warpCharge': engine, 'tint': color, 'color': colors[color], 'runs': runs})

    # These breach locations are the completed showcase's Tug II-A damage sites.
    breaches = [(1,.20,-.38,4.3),(1,.30,.08,3.5),(2,-.27,-.34,5.8),
                (2,-.20,-.15,5.4),(2,-.30,.10,6.6),(2,-.39,.40,4.8),
                (3,.23,-.37,8.2),(3,.12,-.17,7.2),(3,.07,.12,9.5),
                (3,-.15,.26,7.6),(3,.42,.41,6.2)]
    damage = [[], [], [], []]
    for stage in range(1, 4):
        damage[stage] = [{'x': round((x+.5)*width, 3), 'y': round((y+.5)*height, 3), 'r': radius}
                         for first, x, y, radius in breaches if first <= stage]
    sites = [['forward command hull', width*.5, height*.16],
             ['reactor housing', width*.5, height*.58],
             ['port nacelle', width*.12, height*.83], ['starboard nacelle', width*.88, height*.83]]
    profile = {'width': width, 'height': height, 'lights': lights, 'damage': damage,
               'shifts': [[0, 0]]*4, 'sites': sites, 'core': [width*.5, height*.58]}
    target = ART / 'federation-profiles.js'
    target.write_text('/* Measured original Tug II-A lamps; generated by tools/build-federation-profile.py. */\n'
                      'window.earthAnimationProfiles[416]=' + json.dumps(profile, separators=(',', ':')) + ';\n', encoding='utf8')
    print(json.dumps({'ship': 416, 'dimensions': [width, height], 'fixtures': len(lights), 'target': str(target)}))


if __name__ == '__main__':
    build()
